export const translateFactoryValue = (val) => {
  if (val === null || val === undefined || val === '') {
    return 'Not Chosen';
  }

  if (typeof val === 'boolean') {
    return val ? 'Yes' : 'No';
  }

  if (Array.isArray(val)) {
    if (val.length === 0) return 'Not Chosen';
    return val.map(item => translateFactoryValue(item)).join(', ');
  }

  if (typeof val === 'object') {
    if (val.name) return translateFactoryValue(val.name);
    if (val.value) return translateFactoryValue(val.value);
    return JSON.stringify(val);
  }

  const str = String(val).trim();
  if (!str) return 'Not Chosen';

  // 1. Direct exact match
  if (EXACT_TRANSLATIONS[str] !== undefined) {
    return EXACT_TRANSLATIONS[str];
  }

  // 2. Direct case-insensitive lookup
  const lower = str.toLowerCase();
  const exactKey = Object.keys(EXACT_TRANSLATIONS).find(k => k.toLowerCase() === lower);
  if (exactKey) {
    return EXACT_TRANSLATIONS[exactKey];
  }

  // 3. Check for pure numeric / size strings (e.g. "56", "57.5", "2026")
  if (/^\d+(\.\d+)?$/.test(str)) {
    return str;
  }

  // 4. Smart Compound Phrase Word-by-Word Replacement
  // e.g. "Bordeaux / Guld", "Sort hagerem", "Sort velour æske", "UDEN_STEN Guld Simli Guld"
  const words = str.split(/(\s+|[-/+,&_])/);
  let replacedAny = false;
  const translatedWords = words.map(chunk => {
    const trimmed = chunk.trim().toLowerCase();
    if (WORD_TRANSLATIONS[trimmed]) {
      replacedAny = true;
      return WORD_TRANSLATIONS[trimmed];
    }
    const directMatch = Object.keys(EXACT_TRANSLATIONS).find(k => k.toLowerCase() === trimmed);
    if (directMatch) {
      replacedAny = true;
      return EXACT_TRANSLATIONS[directMatch];
    }
    return chunk;
  });

  if (replacedAny) {
    return translatedWords.join('').replace(/_+/g, ' ').replace(/\s+/g, ' ').trim();
  }

  // Fallback: return original text intact (e.g. custom text engravings or customer names)
  return str;
};
